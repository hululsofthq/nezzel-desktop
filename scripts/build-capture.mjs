import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const outDir = new URL('../src-tauri/src/catch/', import.meta.url);
const result = await build({
  configFile: false,
  publicDir: false,
  logLevel: 'error',
  build: {
    write: false,
    // Classic workers serialize two bundled functions, so keep their bodies intact.
    minify: false,
    lib: {
      entry: fileURLToPath(new URL('../src-capture/catch-hooks.ts', import.meta.url)),
      name: 'NezzelCatchHooks',
      formats: ['iife'],
    },
  },
});

const emitted = Array.isArray(result) ? result[0] : result;
const output = emitted.output;
if (output.length !== 1 || output[0].type !== 'chunk') throw new Error('Expected one capture IIFE');
await mkdir(outDir, { recursive: true });
await writeFile(new URL('hooks.js', outDir), '// Generated by pnpm run build:capture.\n' + output[0].code);
