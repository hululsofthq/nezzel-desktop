#!/usr/bin/env node
// Refreshes the ad and tracker list the Nezzel browser blocks with (src-tauri/src/catch/filters/network.txt).
// Run by hand before a release: `node scripts/fetch-filters.mjs`. Keeps network rules only: page-hiding (cosmetic)
// rules and options that rewrite requests or pages are dropped, the browser only blocks requests.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const LISTS = [
  ['EasyList', 'https://easylist.to/easylist/easylist.txt'],
  ['EasyPrivacy', 'https://easylist.to/easylist/easyprivacy.txt'],
];
const OUT = fileURLToPath(new URL('../src-tauri/src/catch/filters/network.txt', import.meta.url));
// WebKit refuses a content-blocker list above this many rules (WebCore ContentExtensionParser maxRuleCount).
const MAX_RULES = 150_000;
const COSMETIC = /#[@?$%]?#|#@[$%?]#/;
const DROPPED_OPTION = /\$(.*,)?~?(csp|redirect|redirect-rule|removeparam|replace|rewrite|header|permissions|urltransform|uritransform|generichide|elemhide|specifichide|ghide|ehide|shide)\b/;

/** Network rules of one list, in order. */
export function networkRules(text) {
  return text
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(line => line && !line.startsWith('!') && !line.startsWith('['))
    .filter(line => !COSMETIC.test(line) && !DROPPED_OPTION.test(line));
}

async function main() {
  const header = ['! Nezzel browser network filters. Generated by scripts/fetch-filters.mjs; do not edit.'];
  const body = [];
  for (const [name, url] of LISTS) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
    const text = await response.text();
    const version = /^! Version: (.+)$/m.exec(text)?.[1] ?? 'unknown';
    const rules = networkRules(text);
    header.push(`! ${name} ${version} <${url}> (GPLv3 or CC BY-SA 3.0, licenses/filters-NOTICE.txt): ${rules.length} rules`);
    body.push(...rules);
  }
  if (body.length > MAX_RULES) throw new Error(`${body.length} rules is above WebKit's ${MAX_RULES}`);
  const content = `${body.join('\n')}\n`;
  header.push(`! sha256 ${createHash('sha256').update(content).digest('hex')}`);
  writeFileSync(OUT, `${header.join('\n')}\n${content}`);
  console.log(`${body.length} rules → ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
